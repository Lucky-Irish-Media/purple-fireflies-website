import "server-only";

import { getCloudflareContext } from "@opennextjs/cloudflare";

/**
 * Community Pet Fund photos live in a private R2 bucket and are served by the
 * Worker at `/api/media/[...key]`. Nothing outside this module talks to R2, so
 * the bucket name, key layout, and validation rules live in one place.
 *
 * Images are resized in the browser before upload (see `PhotoUpload.tsx`).
 * Workers have no `sharp` and OpenNext's image optimizer is friction, so the
 * server accepts an already-small file and stores the bytes untouched.
 */
export const MAX_IMAGE_BYTES = 8 * 1024 * 1024;

/** Only images are ever stored, and the key extension follows the MIME type. */
const EXTENSION_BY_MIME: Record<string, string> = {
  "image/jpeg": "jpg",
  "image/png": "png",
  "image/webp": "webp",
};

export const ALLOWED_IMAGE_TYPES = Object.keys(EXTENSION_BY_MIME);

/** Every key this app writes is under `animals/`. The serve route enforces it. */
const MEDIA_KEY_PREFIX = "animals/";

export function extensionForImageType(mimeType: string): string | null {
  return EXTENSION_BY_MIME[mimeType] ?? null;
}

export function animalPhotoKey(animalId: number, extension: string): string {
  return `${MEDIA_KEY_PREFIX}${animalId}/${crypto.randomUUID()}.${extension}`;
}

/**
 * Keys are generated by this module, never by a browser, but the serve route
 * still validates the shape so a crafted URL cannot walk out of `animals/`.
 */
export function isServableMediaKey(key: string): boolean {
  return (
    key.startsWith(MEDIA_KEY_PREFIX) &&
    key.length > MEDIA_KEY_PREFIX.length &&
    !key.includes("..") &&
    !key.includes("//") &&
    !key.includes("\\")
  );
}

async function getMediaBucket(): Promise<R2Bucket> {
  const { env } = await getCloudflareContext({ async: true });
  return env.MEDIA_BUCKET;
}

export async function putMediaObject(
  key: string,
  body: ArrayBuffer,
  contentType: string,
): Promise<void> {
  const bucket = await getMediaBucket();
  await bucket.put(key, body, {
    httpMetadata: {
      contentType,
      // The serve route sets the long-lived cache header; storing it here too
      // keeps the object honest if it is ever read directly.
      cacheControl: "public, max-age=31536000, immutable",
    },
  });
}

/**
 * Removing an object that is already gone is not an error: the row is the
 * source of truth and a retry must not fail on cleanup.
 */
export async function deleteMediaObject(key: string): Promise<void> {
  if (!isServableMediaKey(key)) return;
  const bucket = await getMediaBucket();
  await bucket.delete(key);
}

export async function getMediaObject(key: string): Promise<R2ObjectBody | null> {
  if (!isServableMediaKey(key)) return null;
  const bucket = await getMediaBucket();
  return bucket.get(key);
}
